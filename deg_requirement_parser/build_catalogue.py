#!/usr/bin/env python3
"""
Combine one classifier run into a single requirements file for the whole catalogue.

Reads every <out-dir>/<stem>.json, runs the same checks as check_results.py,
and writes one JSON file with:

  - where it came from: catalogue year, model, prompt, taxonomy version, date
  - one entry per programme that passes every check: the scraper's header
    (name, credential, catalogue URL, content hash) plus the requirement tree
  - per programme, what code can't fully check: unresolved pools, placeholder
    leaves, unclassified entries by reason, and the check warnings
  - "not_included": programmes that failed a check, with the first errors

Usage
    python build_catalogue.py --out-dir out_v2
    python build_catalogue.py --out-dir out_v2 --output /tmp/requirements.json

The output is only as good as the run. See README.md, "Where it might be wrong".
"""

from __future__ import annotations

import argparse
import csv
import json
import re
from datetime import datetime, timezone
from pathlib import Path

import bip
from check_results import PROGRAMS_DIR, check_program
from check_taxonomy import load_schema, validators

HERE = Path(__file__).resolve().parent
DEFAULT_OUTPUT = HERE / "catalogue" / "usc_degree_requirements_2026_2027.json"
HEADER_FIELDS = {
    "Program Name": "name",
    "Credential": "credential",
    "School or Academic Unit": "school",
    "Catalogue Year": "catalogue_year",
    "Program Identifier": "program_id",
    "Canonical URL": "catalogue_url",
    "Content SHA-256": "content_sha256",
    "Retrieved At": "retrieved_at",
}


def header(stem: str) -> dict:
    """The scraper's header lines ("Program Name: Economics (BA)") as a dict."""
    out = {"stem": stem}
    src = PROGRAMS_DIR / f"{stem}.txt"
    if not src.exists():
        return out
    for line in src.read_text(encoding="utf-8").split("\n")[:15]:
        key, _, value = line.partition(":")
        if key in HEADER_FIELDS:
            out[HEADER_FIELDS[key]] = value.strip() or None
    return out


def taxonomy_version() -> str:
    m = re.search(r"^Version (\S+)", (HERE / "constraint_taxonomy.md").read_text(encoding="utf-8"), re.M)
    return m.group(1).rstrip(".") if m else "unknown"


def run_model(out_dir: Path) -> str | None:
    meta = out_dir / "run_meta.csv"
    if meta.exists():
        rows = list(csv.DictReader(meta.open(encoding="utf-8")))
        if rows:
            return rows[0].get("model")
    return None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", default="out_v2", help="classifier output folder (default: out_v2)")
    ap.add_argument("--output", default=str(DEFAULT_OUTPUT), help="file to write")
    args = ap.parse_args()
    out_dir = HERE / args.out_dir

    vals = validators(load_schema())
    programmes, excluded = [], []
    for path in sorted(out_dir.glob("*.json")):
        row, errors, warnings = check_program(path, vals)
        if errors:
            excluded.append({"stem": path.stem, "errors": errors[:5], "error_count": len(errors)})
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        audit = bip.audit(data)
        programmes.append({
            **header(path.stem),
            "requirements": {k: data[k] for k in ("program", "status", "root", "unclassified")},
            "review": {
                "unresolved_terms": row["unresolved"],
                "needs_data": [f"{a.path}: {a.detail}" for a in audit if a.status == "needs data"],
                "not_checked_by_code": [f"{a.path}: {a.what}" for a in audit if a.status == "LOST"],
                "unclassified_by_reason": {r: row[f"unc_{r}"] for r in
                                           ("no_fit", "out_of_scope", "university_level", "advisory")},
                "low_confidence_nodes": row["low_confidence"],
                "warnings": warnings,
            },
        })

    total_txt = len(list(PROGRAMS_DIR.glob("*.txt")))
    result = {
        "about": ("USC undergraduate degree requirements as machine-checkable trees, one per programme. "
                  "Generated by deg_requirement_parser from the catalogue scrape; see its README for "
                  "the format, how to regenerate it, and where it might be wrong. Not an official USC source."),
        "catalogue_year": "2026-2027",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "model": run_model(out_dir),
        "prompt": "docs/prompt_v2.txt",
        "taxonomy_version": taxonomy_version(),
        "schema": "deg_requirement_parser/requirement_schema.json",
        "counts": {
            "programmes_in_catalogue": total_txt,
            "classified": len(programmes) + len(excluded),
            "included": len(programmes),
            "not_included": len(excluded),
        },
        "programmes": programmes,
        "not_included": excluded,
    }
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {output}: {len(programmes)} programmes included, {len(excluded)} not included "
          f"(of {total_txt} in the catalogue).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
